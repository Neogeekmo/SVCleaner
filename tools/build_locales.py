"""Build the self-contained WoW locale catalog; no runtime dependency."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def build():
    data = json.loads((ROOT / "addon" / "locales" / "locales.json").read_text(encoding="utf-8"))
    data["locales"].update(json.loads((ROOT / "addon" / "locales" / "translations.json").read_text(encoding="utf-8")))
    grid = json.loads((ROOT / "addon" / "locales" / "grid_locales.json").read_text(encoding="utf-8"))
    data["keys"].extend(grid["keys"])
    for locale, values in data["locales"].items():
        values.extend(grid["locales"][locale])
    data["locales"]["esMX"] = list(data["locales"]["esES"])
    keys = data["keys"]
    lines = ["-- Generated by tools/build_locales.py; edit addon/locales/.", "local _, SVC = ...", "local keys = " + json.dumps(keys, ensure_ascii=False).replace("[", "{", 1).rsplit("]", 1)[0] + "}", "SVC.Locales = {}"]
    for locale, values in data["locales"].items():
        if len(values) != len(keys) or any(not value for value in values):
            raise ValueError(f"{locale}: expected {len(keys)} non-empty translations, got {len(values)}")
        lines.append("do local values = {")
        lines.extend("    " + json.dumps(value, ensure_ascii=False) + "," for value in values)
        lines.extend(["}; local catalog = {}; for i, key in ipairs(keys) do catalog[key] = values[i] end", f'SVC.Locales["{locale}"] = catalog; end'])
    lines.extend(['SVC.Locales.enGB = SVC.Locales.enUS', 'SVC.Locales.ptPT = SVC.Locales.ptBR',
                  'SVC.locale = type(GetLocale) == "function" and GetLocale() or "enUS"',
                  'SVC.L = setmetatable({}, {__index = function(_, key) return (SVC.Locales[SVC.locale] or SVC.Locales.enUS)[key] or SVC.Locales.enUS[key] or key end})',
                  'SVC.font = STANDARD_TEXT_FONT or (GameFontNormal and select(1, GameFontNormal:GetFont())) or "Fonts\\\\FRIZQT__.TTF"'])
    (ROOT / "addon" / "Locale.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(keys)} strings, {len(data['locales'])} full catalogs + enGB/ptPT aliases")


if __name__ == "__main__":
    build()
